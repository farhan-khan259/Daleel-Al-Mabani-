function initReveal() {
  const revealItems = document.querySelectorAll('.reveal');
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add('is-visible');
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12, rootMargin: '0px 0px -40px 0px' });

  revealItems.forEach((item) => observer.observe(item));
}

function animateCounters() {
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;
      const el = entry.target;
      const target = Number(el.getAttribute('data-target') || el.getAttribute('data-count'));
      const isPercent = target === 98;
      const duration = 1500;
      const start = performance.now();
      const step = (timestamp) => {
        const progress = Math.min((timestamp - start) / duration, 1);
        const eased = 1 - Math.pow(1 - progress, 3);
        const value = Math.floor(eased * target);
        el.textContent = isPercent && el.classList.contains('counter') ? `${value}%` : (el.classList.contains('counter') ? `${value}+` : `${value}`);
        if (progress < 1) requestAnimationFrame(step);
        else el.textContent = isPercent && el.classList.contains('counter') ? `${target}%` : (el.classList.contains('counter') ? `${target}+` : `${target}`);
      };
      requestAnimationFrame(step);
      observer.unobserve(el);
    });
  }, { threshold: 0.6 });

  counters.forEach((counter) => observer.observe(counter));
}

